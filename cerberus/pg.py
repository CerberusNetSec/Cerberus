"""Clustered storage: PostgreSQL for alerts, devices, settings and the rest,
ClickHouse (ch.py) for events and per-minute counters.

PostgresStore implements the whole storage contract (storage.py): the
relational operations here, with the same meaning as the SQLite backend, and
the event and counter operations by handing them to ClickHouseEvents. Text
search is case-insensitive (ILIKE), like SQLite's LIKE, and every ordering
breaks ties the same way as the SQLite backend.

A Batch is written to ClickHouse and then to PostgreSQL. The two are not one
transaction: if the second write fails, that second's events are stored and
its alert changes are not (they are logged and lost, as a failed SQLite write
loses the whole second).
"""
from __future__ import annotations

import json
import queue
from contextlib import contextmanager

from .ch import ClickHouseEvents
from .models import SEVERITIES
from .storage import Batch, Leadership, Store

POOL = 6

SCHEMA = """
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT PRIMARY KEY,
    created DOUBLE PRECISION NOT NULL, last_seen DOUBLE PRECISION NOT NULL,
    detector TEXT, severity TEXT, title TEXT, description TEXT, entity TEXT,
    src_ip TEXT, device TEXT, count INTEGER DEFAULT 1,
    status TEXT DEFAULT 'open', details TEXT, updated DOUBLE PRECISION DEFAULT 0
);
CREATE INDEX IF NOT EXISTS alerts_last ON alerts(last_seen);
CREATE INDEX IF NOT EXISTS alerts_status ON alerts(status, last_seen);
CREATE INDEX IF NOT EXISTS alerts_updated ON alerts(updated, id);
CREATE TABLE IF NOT EXISTS devices (
    id TEXT PRIMARY KEY, ip TEXT, hostname TEXT, name TEXT DEFAULT '',
    connector_pin TEXT DEFAULT '', connector_seen TEXT DEFAULT '',
    first_seen DOUBLE PRECISION, last_seen DOUBLE PRECISION, events BIGINT DEFAULT 0,
    snmp_mode TEXT DEFAULT 'default', snmp_community TEXT DEFAULT '', snmp_host TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS snmp_data (
    device TEXT PRIMARY KEY, polled DOUBLE PRECISION, ok INTEGER, error TEXT, last_ok DOUBLE PRECISION, data TEXT
);
CREATE TABLE IF NOT EXISTS channels (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL, name TEXT NOT NULL, enabled INTEGER DEFAULT 1, min_severity TEXT DEFAULT 'medium',
    config TEXT DEFAULT '{}', last_ts DOUBLE PRECISION, last_ok INTEGER, last_error TEXT
);
CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, expires DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS sites (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE, token_hash TEXT UNIQUE, managed INTEGER DEFAULT 0,
    created DOUBLE PRECISION, last_seen DOUBLE PRECISION, silent INTEGER DEFAULT 0,
    address TEXT, version TEXT, reported_name TEXT, instance TEXT, summary TEXT
);
CREATE TABLE IF NOT EXISTS site_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id INTEGER NOT NULL, instance TEXT NOT NULL, alert_id BIGINT NOT NULL,
    created DOUBLE PRECISION, last_seen DOUBLE PRECISION, received DOUBLE PRECISION,
    detector TEXT, severity TEXT, title TEXT, description TEXT, entity TEXT,
    src_ip TEXT, device TEXT, count INTEGER, details TEXT,
    status TEXT DEFAULT 'open', pending TEXT,
    UNIQUE (site_id, instance, alert_id)
);
CREATE INDEX IF NOT EXISTS site_alerts_last ON site_alerts(last_seen);
CREATE INDEX IF NOT EXISTS site_alerts_status ON site_alerts(status, last_seen);
"""

ALERT_COLUMNS = ("id", "created", "last_seen", "detector", "severity", "title", "description", "entity",
                 "src_ip", "device", "count", "status", "details", "updated")


class _AdvisoryLock(Leadership):
    """A session-level advisory lock on a connection of its own. PostgreSQL frees it the
    moment that session ends: at once if the holder exits or crashes, within about 25
    seconds (TCP keepalives) if the holder's host or network disappears."""

    CLASS = 7243  # first half of the two-part lock key; the second is a hash of the name

    def __init__(self, url: str, name: str):
        self.url = url
        self.name = name
        self.conn = None

    def _connect(self):
        import psycopg
        conn = psycopg.connect(self.url, autocommit=True, connect_timeout=5, keepalives=1, keepalives_idle=10,
                               keepalives_interval=5, keepalives_count=3)
        # The server side too: notice a vanished holder and free its lock.
        for setting in ("tcp_keepalives_idle = 10", "tcp_keepalives_interval = 5", "tcp_keepalives_count = 3",
                        "statement_timeout = 5000"):
            conn.execute(f"SET {setting}")
        return conn

    def try_acquire(self) -> bool:
        if self.conn is None or self.conn.closed:
            self.conn = self._connect()
        row = self.conn.execute("SELECT pg_try_advisory_lock(%s, hashtext(%s))", (self.CLASS, self.name)).fetchone()
        return bool(row[0])

    def still_held(self) -> bool:
        if self.conn is None or self.conn.closed:
            return False
        try:
            # A session lock lasts as long as the session: alive means still held.
            self.conn.execute("SELECT 1").fetchone()
            return True
        except Exception:
            return False

    def release(self) -> None:
        if self.conn is not None and not self.conn.closed:
            try:
                self.conn.close()
            except Exception:
                pass
        self.conn = None


class PostgresStore(Store):
    def __init__(self, url: str, events: ClickHouseEvents):
        import psycopg  # optional dependency: only clustered storage needs it
        from psycopg.rows import dict_row

        self.events = events
        self._url = url
        self._pool: queue.SimpleQueue = queue.SimpleQueue()
        self._conns = [psycopg.connect(url, autocommit=True, row_factory=dict_row) for _ in range(POOL)]
        for conn in self._conns:
            self._pool.put(conn)
        with self._tx() as conn:
            # Several processes (collectors, processor) may start at once: one creates the tables.
            conn.execute("SELECT pg_advisory_xact_lock(7243829041)")
            conn.execute(SCHEMA)

    # --- plumbing -------------------------------------------------------------------------
    @contextmanager
    def _conn(self):
        conn = self._pool.get()
        try:
            yield conn
        finally:
            self._pool.put(conn)

    @contextmanager
    def _tx(self):
        with self._conn() as conn, conn.transaction():
            yield conn

    def _q(self, sql: str, params=()) -> list[dict]:
        with self._conn() as conn:
            return conn.execute(sql, params).fetchall()

    def _x(self, sql: str, params=()) -> int:
        with self._conn() as conn:
            return conn.execute(sql, params).rowcount

    def close(self) -> None:
        for conn in self._conns:
            conn.close()
        self.events.close()

    # --- settings -------------------------------------------------------------------------------
    def get_setting(self, key: str, default=None):
        rows = self._q("SELECT value FROM settings WHERE key = %s", (key,))
        if not rows:
            return default
        try:
            return json.loads(rows[0]["value"])
        except ValueError:
            return default

    def leadership(self, name: str) -> Leadership:
        return _AdvisoryLock(self._url, name)

    def settings_with_prefix(self, prefix: str) -> dict:
        out = {}
        for row in self._q("SELECT key, value FROM settings WHERE left(key, length(%s)) = %s", (prefix, prefix)):
            try:
                out[row["key"]] = json.loads(row["value"])
            except ValueError:
                pass
        return out

    def set_setting(self, key: str, value) -> None:
        self._x("INSERT INTO settings(key, value) VALUES(%s, %s) ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                (key, json.dumps(value)))

    # --- the pipeline's writes -------------------------------------------------------------------
    def write_batch(self, batch: Batch) -> None:
        self.events.write(batch.events, batch.stats, batch.ports)
        if not (batch.devices or batch.new_alerts or batch.alert_updates):
            return
        with self._tx() as conn, conn.cursor() as cur:
            if batch.devices:
                cur.executemany(
                    "INSERT INTO devices(id, ip, hostname, connector_seen, first_seen, last_seen, events) "
                    "VALUES(%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(id) DO UPDATE SET ip = excluded.ip, "
                    "hostname = excluded.hostname, connector_seen = excluded.connector_seen, "
                    "last_seen = excluded.last_seen, events = excluded.events", batch.devices)
            if batch.new_alerts:
                cur.executemany(
                    f"INSERT INTO alerts({', '.join(ALERT_COLUMNS)}) VALUES({', '.join(['%s'] * len(ALERT_COLUMNS))}) "
                    "ON CONFLICT(id) DO UPDATE SET "
                    + ", ".join(f"{c} = excluded.{c}" for c in ALERT_COLUMNS[1:]), batch.new_alerts)
            if batch.alert_updates:
                cur.executemany("UPDATE alerts SET last_seen=%s, count=%s, severity=%s, description=%s, details=%s, "
                                "updated=%s WHERE id=%s", batch.alert_updates)

    def prune(self, now: float, retention_days: int, max_events: int, alert_days: int) -> int:
        removed = self.events.prune(now - retention_days * 86400, max_events)
        self._x("DELETE FROM alerts WHERE last_seen < %s", (now - alert_days * 86400,))
        self._x("DELETE FROM site_alerts WHERE last_seen < %s", (now - alert_days * 86400,))
        self._x("DELETE FROM sessions WHERE expires < %s", (now,))
        return removed

    # --- events and counters: ClickHouse ------------------------------------------------------------
    def search_events(self, since: float = 0, before: int = 0, limit: int = 200, timeout: float = 0, *,
                      device: str = "", event_type: str = "", action: str = "", ip: str = "",
                      port: int | None = None, text: str = "") -> list[dict]:
        return self.events.search_events(since, before, limit, timeout, device=device, event_type=event_type,
                                         action=action, ip=ip, port=port, text=text)

    def events_stored(self) -> int:
        return self.events.events_stored()

    def oldest_event_ts(self) -> float | None:
        return self.events.oldest_event_ts()

    def traffic_series(self, start: int, bucket: int) -> list[dict]:
        return self.events.traffic_series(start, bucket)

    def traffic_totals(self, since: int) -> tuple[int, int]:
        return self.events.traffic_totals(since)

    def ensure_stats_totals(self) -> None:
        pass  # the all-devices row has been written with every batch since the start

    def port_series(self, start: int, bucket: int) -> list[dict]:
        return self.events.port_series(start, bucket)

    def port_minutes_since(self, minute: int) -> list[dict]:
        return self.events.port_minutes_since(minute)

    # --- alerts -------------------------------------------------------------------------------------
    def alert_next_id(self) -> int:
        return (self._q("SELECT MAX(id) AS m FROM alerts")[0]["m"] or 0) + 1

    def alerts_active_since(self, last_seen: float) -> list[dict]:
        return self._q("SELECT * FROM alerts WHERE status != 'resolved' AND last_seen > %s", (last_seen,))

    @staticmethod
    def _alert_filters(prefix: str, status: str, severity: str, text: str) -> tuple[list[str], list]:
        where, params = [], []
        if status in ("open", "ack", "resolved"):
            where.append(f"{prefix}status = %s")
            params.append(status)
        elif status == "active":
            where.append(f"{prefix}status != 'resolved'")
        if severity in SEVERITIES:
            wanted = SEVERITIES[SEVERITIES.index(severity):]
            where.append(f"{prefix}severity = ANY(%s)")
            params.append(wanted)
        if text:
            where.append(f"({prefix}title ILIKE %s OR {prefix}description ILIKE %s OR {prefix}src_ip ILIKE %s "
                         f"OR {prefix}device ILIKE %s)")
            params += [f"%{text}%"] * 4
        return where, params

    def alerts_find(self, *, status: str = "", severity: str = "", text: str = "", limit: int = 200,
                    alert_id: int = 0) -> list[dict]:
        if alert_id:
            more, extra = self._alert_filters("", "", severity, text)
            where, params = ["id = %s", *more], [alert_id, *extra]
        else:
            where, params = self._alert_filters("", status, severity, text)
        sql = "SELECT * FROM alerts" + (" WHERE " + " AND ".join(where) if where else "")
        return self._q(sql + " ORDER BY last_seen DESC, id DESC LIMIT %s", (*params, limit))

    def alerts_recent(self, limit: int) -> list[dict]:
        return self._q("SELECT id, created, last_seen, severity, title, description, status, count FROM alerts "
                       "ORDER BY last_seen DESC, id DESC LIMIT %s", (limit,))

    def alerts_unresolved_since(self, last_seen: float, limit: int) -> list[dict]:
        return self._q("SELECT id, detector, severity, title, last_seen, src_ip, device, details FROM alerts "
                       "WHERE status != 'resolved' AND last_seen >= %s ORDER BY last_seen DESC, id DESC LIMIT %s",
                       (last_seen, limit))

    def alert_counts_open(self) -> dict[str, int]:
        return {r["severity"]: r["n"] for r in self._q(
            "SELECT severity, COUNT(*) AS n FROM alerts WHERE status = 'open' GROUP BY severity")}

    def alert_counts_open_by_device(self) -> dict[str, dict[str, int]]:
        out: dict[str, dict[str, int]] = {}
        for row in self._q("SELECT device, severity, COUNT(*) AS n FROM alerts WHERE status = 'open' "
                           "GROUP BY device, severity"):
            out.setdefault(row["device"] or "", {})[row["severity"]] = row["n"]
        return out

    def alert_ids_open(self) -> list[int]:
        return [r["id"] for r in self._q("SELECT id FROM alerts WHERE status = 'open' ORDER BY id")]

    def set_alert_status(self, ids: list[int], status: str, stamp: float) -> None:
        for start in range(0, len(ids), 500):
            self._x("UPDATE alerts SET status = %s, updated = %s WHERE id = ANY(%s)",
                    (status, stamp, ids[start:start + 500]))

    def alert_changes_since(self, updated: float, alert_id: int, limit: int) -> list[dict]:
        return self._q(
            "SELECT id, created, last_seen, updated, detector, severity, title, description, entity, src_ip, device, "
            "count, status, details FROM alerts WHERE updated > %s OR (updated = %s AND id > %s) "
            "ORDER BY updated, id LIMIT %s", (updated, updated, alert_id, limit))

    # --- devices -------------------------------------------------------------------------------------
    def devices_all(self) -> list[dict]:
        return self._q("SELECT * FROM devices ORDER BY first_seen, id")

    def update_device(self, device_id: str, name: str, connector_pin: str, snmp_mode: str,
                      snmp_community: str, snmp_host: str) -> None:
        self._x("UPDATE devices SET name=%s, connector_pin=%s, snmp_mode=%s, snmp_community=%s, snmp_host=%s "
                "WHERE id=%s", (name, connector_pin, snmp_mode, snmp_community, snmp_host, device_id))

    def forget_device(self, device_id: str) -> None:
        with self._tx() as conn:
            conn.execute("DELETE FROM devices WHERE id = %s", (device_id,))
            conn.execute("DELETE FROM snmp_data WHERE device = %s", (device_id,))

    # --- notification channels -----------------------------------------------------------------------
    def channels(self) -> list[dict]:
        return self._q("SELECT * FROM channels ORDER BY id")

    def channel(self, channel_id: int) -> dict | None:
        rows = self._q("SELECT * FROM channels WHERE id = %s", (channel_id,))
        return rows[0] if rows else None

    def add_channel(self, row: dict) -> int:
        return self._q("INSERT INTO channels(type, name, enabled, min_severity, config) VALUES(%s,%s,%s,%s,%s) "
                       "RETURNING id", (row["type"], row["name"], row["enabled"], row["min_severity"], row["config"]))[0]["id"]

    def update_channel(self, channel_id: int, row: dict) -> None:
        self._x("UPDATE channels SET name=%s, enabled=%s, min_severity=%s, config=%s WHERE id=%s",
                (row["name"], row["enabled"], row["min_severity"], row["config"], channel_id))

    def delete_channel(self, channel_id: int) -> None:
        self._x("DELETE FROM channels WHERE id = %s", (channel_id,))

    def channel_result(self, channel_id: int, when: float, ok: bool, error: str | None) -> None:
        self._x("UPDATE channels SET last_ts=%s, last_ok=%s, last_error=%s WHERE id=%s",
                (when, 1 if ok else 0, error, channel_id))

    # --- SNMP ---------------------------------------------------------------------------------------------
    def snmp_records(self) -> list[dict]:
        return self._q("SELECT * FROM snmp_data")

    def save_snmp_record(self, device: str, polled: float, ok: bool, error: str, last_ok: float | None,
                         data: str | None) -> None:
        self._x("INSERT INTO snmp_data(device, polled, ok, error, last_ok, data) VALUES(%s,%s,%s,%s,%s,%s) "
                "ON CONFLICT(device) DO UPDATE SET polled = excluded.polled, ok = excluded.ok, "
                "error = excluded.error, last_ok = excluded.last_ok, data = excluded.data",
                (device, polled, int(ok), error, last_ok, data))

    # --- migration ---------------------------------------------------------------------------------------
    def import_table(self, table: str, rows: list[dict]) -> None:
        columns = self.IMPORTABLE[table]
        with self._tx() as conn, conn.cursor() as cur:
            cur.executemany(f"INSERT INTO {table}({', '.join(columns)}) VALUES({', '.join(['%s'] * len(columns))})",
                            [tuple(row.get(c) for c in columns) for row in rows])
            if table in ("channels", "sites", "site_alerts") and rows:
                # Ids were given explicitly: move the identity sequence past them.
                cur.execute(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                            f"(SELECT MAX(id) FROM {table}))")

    # --- dashboard sessions ----------------------------------------------------------------------------
    def session_add(self, token_hash: str, expires: float) -> None:
        self._x("INSERT INTO sessions(token_hash, expires) VALUES(%s, %s) "
                "ON CONFLICT(token_hash) DO UPDATE SET expires = excluded.expires", (token_hash, expires))

    def session_expires(self, token_hash: str) -> float | None:
        rows = self._q("SELECT expires FROM sessions WHERE token_hash = %s", (token_hash,))
        return rows[0]["expires"] if rows else None

    def session_delete(self, token_hash: str) -> None:
        self._x("DELETE FROM sessions WHERE token_hash = %s", (token_hash,))

    # --- central console: sites and their alerts --------------------------------------------------------
    def sites_provision(self, entries: list[tuple[str, str]], now: float) -> None:
        with self._tx() as conn:
            for name, digest in entries:
                conn.execute("UPDATE sites SET token_hash = NULL, managed = 0 WHERE token_hash = %s AND name != %s",
                             (digest, name))
                if conn.execute("UPDATE sites SET token_hash = %s, managed = 1 WHERE name = %s",
                                (digest, name)).rowcount == 0:
                    conn.execute("INSERT INTO sites(name, token_hash, created, managed) VALUES(%s,%s,%s,1)",
                                 (name, digest, now))

    def site_create(self, name: str, token_hash: str, now: float) -> int:
        with self._tx() as conn:
            if conn.execute("SELECT 1 FROM sites WHERE name = %s", (name,)).fetchone():
                raise ValueError("A site with that name already exists.")
            return conn.execute("INSERT INTO sites(name, token_hash, created) VALUES(%s,%s,%s) RETURNING id",
                                (name, token_hash, now)).fetchone()["id"]

    def site_rotate(self, site_id: int, token_hash: str) -> bool:
        return self._x("UPDATE sites SET token_hash = %s WHERE id = %s AND managed = 0", (token_hash, site_id)) > 0

    def site_delete(self, site_id: int) -> None:
        with self._tx() as conn:
            row = conn.execute("SELECT managed FROM sites WHERE id = %s", (site_id,)).fetchone()
            if row is None:
                raise LookupError(site_id)
            if row["managed"]:
                raise ValueError("This site is set in configuration; remove it there instead.")
            conn.execute("DELETE FROM site_alerts WHERE site_id = %s", (site_id,))
            conn.execute("DELETE FROM sites WHERE id = %s", (site_id,))

    def site(self, site_id: int) -> dict | None:
        rows = self._q("SELECT * FROM sites WHERE id = %s", (site_id,))
        return rows[0] if rows else None

    def sites_all(self) -> list[dict]:
        return self._q("SELECT * FROM sites ORDER BY name")

    def site_alert_open_counts(self) -> dict[int, dict[str, int]]:
        out: dict[int, dict[str, int]] = {}
        for row in self._q("SELECT site_id, severity, COUNT(*) AS n FROM site_alerts WHERE status = 'open' "
                           "GROUP BY site_id, severity"):
            out.setdefault(row["site_id"], {})[row["severity"]] = row["n"]
        return out

    def site_report(self, token_hash: str, instance: str, meta: dict, alerts: list[dict],
                    now: float) -> tuple[int, str, list[dict], list[dict]] | None:
        fresh: list[dict] = []
        with self._tx() as conn:
            site = conn.execute("SELECT id, name FROM sites WHERE token_hash = %s", (token_hash,)).fetchone()
            if site is None:
                return None
            site_id, site_name = site["id"], site["name"]
            conn.execute("UPDATE sites SET last_seen = %s, address = %s, version = %s, reported_name = %s, "
                         "instance = %s, summary = %s, silent = 0 WHERE id = %s",
                         (now, meta["address"], meta["version"], meta["reported_name"], instance, meta["summary"],
                          site_id))
            for row in alerts:
                found = conn.execute("SELECT id, pending FROM site_alerts WHERE site_id = %s AND instance = %s "
                                     "AND alert_id = %s", (site_id, instance, row["alert_id"])).fetchone()
                fields = (row["created"], row["last_seen"], now, row["detector"], row["severity"], row["title"],
                          row["description"], row["entity"], row["src_ip"], row["device"], row["count"], row["details"])
                if found is None:
                    new_id = conn.execute(
                        "INSERT INTO site_alerts(site_id, instance, alert_id, created, last_seen, received, detector, "
                        "severity, title, description, entity, src_ip, device, count, details, status) "
                        "VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id",
                        (site_id, instance, row["alert_id"], *fields, row["status"])).fetchone()["id"]
                    if row["status"] == "open":
                        fresh.append({**row, "id": new_id})
                    continue
                status, pending = row["status"], found["pending"]
                if pending:
                    status, pending = (status, None) if status == pending else (pending, pending)
                conn.execute(
                    "UPDATE site_alerts SET created = %s, last_seen = %s, received = %s, detector = %s, severity = %s, "
                    "title = %s, description = %s, entity = %s, src_ip = %s, device = %s, count = %s, details = %s, "
                    "status = %s, pending = %s WHERE id = %s", (*fields, status, pending, found["id"]))
            pending = [{"id": r["alert_id"], "status": r["pending"]} for r in conn.execute(
                "SELECT alert_id, pending FROM site_alerts WHERE site_id = %s AND instance = %s AND pending IS NOT NULL "
                "ORDER BY id LIMIT 5000", (site_id, instance)).fetchall()]
        return site_id, site_name, fresh, pending

    def site_alerts_find(self, *, site_id: int = 0, status: str = "", severity: str = "", text: str = "",
                         limit: int = 200, alert_id: int = 0) -> list[dict]:
        if alert_id:
            where, params = ["a.id = %s"], [alert_id]
        else:
            where, params = self._alert_filters("a.", status, severity, text)
            if site_id:
                where.insert(0, "a.site_id = %s")
                params.insert(0, site_id)
        return self._q("SELECT a.*, s.name AS site FROM site_alerts a JOIN sites s ON s.id = a.site_id"
                       + (" WHERE " + " AND ".join(where) if where else "")
                       + " ORDER BY a.last_seen DESC, a.id DESC LIMIT %s", (*params, limit))

    def site_alerts_set_status(self, ids: list[int], status: str) -> int:
        changed = 0
        for start in range(0, len(ids), 500):
            changed += self._x("UPDATE site_alerts SET status = %s, pending = %s WHERE status != %s AND id = ANY(%s)",
                               (status, status, status, ids[start:start + 500]))
        return changed

    def sites_newly_silent(self, cutoff: float) -> list[dict]:
        with self._tx() as conn:
            rows = conn.execute("UPDATE sites SET silent = 1 WHERE silent = 0 AND last_seen IS NOT NULL "
                                "AND last_seen < %s RETURNING id, name, last_seen", (cutoff,)).fetchall()
        return sorted(rows, key=lambda r: r["id"])
