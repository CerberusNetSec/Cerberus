#!/usr/bin/env python3
"""Generate the secrets for a central console and its sites.

    python deploy/make-secrets.py north south          # sites named north and south
    python deploy/make-secrets.py --out /secure/place north
    python deploy/make-secrets.py --storage            # for compose/clustered-storage.yml

Writes, into deploy/secrets/ unless --out is given (that folder is git-ignored):

    central_password.txt   dashboard password for the console
    site_tokens.txt        "<site> <token>" per line: the console's CERBERUS_SITE_TOKENS_FILE
    <site>.token           that site's CERBERUS_CENTRAL_TOKEN_FILE
    <site>_password.txt    that site's own dashboard password

and with --storage, for compose/clustered-storage.yml:

    storage_password.txt              dashboard password
    storage_postgres_password.txt     database passwords ...
    storage_clickhouse_password.txt
    storage_postgres_url.txt          ... and the URLs Cerberus connects with
    storage_clickhouse_url.txt

Existing files are kept, so adding a site later does not change the others'
tokens. Standard library only.
"""
from __future__ import annotations

import argparse
import re
import secrets
import sys
from pathlib import Path

NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")


def write_once(path: Path, text: str) -> bool:
    if path.exists():
        return False
    # Unix line endings even on Windows: database images read these files byte for byte.
    path.write_bytes(text.encode("utf-8"))
    try:
        # Readable by the container's unprivileged user when bind-mounted (Compose without Swarm).
        path.chmod(0o644)
    except OSError:
        pass
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sites", nargs="*", help="site names: letters, digits, dot, dash, underscore")
    ap.add_argument("--storage", action="store_true", help="also the secrets for compose/clustered-storage.yml")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "secrets")
    args = ap.parse_args()
    if not args.sites and not args.storage:
        ap.error("name at least one site, or give --storage")
    bad = [s for s in args.sites if not NAME.match(s)]
    if bad:
        print(f"not a usable site name: {', '.join(bad)}", file=sys.stderr)
        return 2
    args.out.mkdir(parents=True, exist_ok=True)
    made = []
    if args.storage:
        for name in ("storage_password", "storage_postgres_password", "storage_clickhouse_password"):
            if write_once(args.out / f"{name}.txt", secrets.token_urlsafe(18) + "\n"):
                made.append(f"{name}.txt")
        pg = (args.out / "storage_postgres_password.txt").read_text(encoding="utf-8").strip()
        ch = (args.out / "storage_clickhouse_password.txt").read_text(encoding="utf-8").strip()
        for name, url in (("storage_postgres_url", f"postgresql://cerberus:{pg}@postgres:5432/cerberus"),
                          ("storage_clickhouse_url", f"http://cerberus:{ch}@clickhouse:8123/cerberus")):
            if write_once(args.out / f"{name}.txt", url + "\n"):
                made.append(f"{name}.txt")
        if not args.sites:
            print(f"secrets in {args.out}")
            print("created: " + (", ".join(made) if made else "nothing new (existing files kept)"))
            return 0
    if write_once(args.out / "central_password.txt", secrets.token_urlsafe(18) + "\n"):
        made.append("central_password.txt")
    for site in args.sites:
        if write_once(args.out / f"{site}.token", secrets.token_urlsafe(32) + "\n"):
            made.append(f"{site}.token")
        if write_once(args.out / f"{site}_password.txt", secrets.token_urlsafe(18) + "\n"):
            made.append(f"{site}_password.txt")
    # The console's list is rebuilt from every *.token file, so it always matches them.
    lines = ["# site-name token  (generated by make-secrets.py)"]
    for token_file in sorted(args.out.glob("*.token")):
        lines.append(f"{token_file.stem} {token_file.read_text(encoding='utf-8').strip()}")
    (args.out / "site_tokens.txt").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    try:
        (args.out / "site_tokens.txt").chmod(0o644)
    except OSError:
        pass
    print(f"secrets in {args.out}")
    print("created: " + (", ".join(made) if made else "nothing new (existing files kept)"))
    print(f"sites known to the console: {len(lines) - 1}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
